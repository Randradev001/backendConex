IF OBJECT_ID(N'dbo.CAPETIQUETA_VIRTUAL', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.CAPETIQUETA_VIRTUAL
  (
    CAPVId bigint IDENTITY(1,1) NOT NULL,
    EmpCod smallint NOT NULL,
    TempCod char(9) NOT NULL,
    Ordpnum decimal(10,0) NOT NULL,
    CAPVCodigo char(23) NOT NULL,
    CAPVEstado smallint NOT NULL CONSTRAINT DF_CAPETIQUETA_VIRTUAL_ESTADO DEFAULT (0),
    CAPVLoginC char(10) NULL,
    CAPVFecC datetime NOT NULL CONSTRAINT DF_CAPETIQUETA_VIRTUAL_FECC DEFAULT (GETDATE()),
    CAPVLoginLectura char(10) NULL,
    CAPVFecLectura datetime NULL,
    CONSTRAINT PK_CAPETIQUETA_VIRTUAL PRIMARY KEY (CAPVId),
    CONSTRAINT UQ_CAPETIQUETA_VIRTUAL_CODIGO UNIQUE (EmpCod, TempCod, CAPVCodigo),
    CONSTRAINT CK_CAPETIQUETA_VIRTUAL_ESTADO CHECK (CAPVEstado IN (0,1))
  );

  CREATE INDEX IX_CAPETIQUETA_VIRTUAL_ORDEN
    ON dbo.CAPETIQUETA_VIRTUAL (EmpCod, TempCod, Ordpnum, CAPVEstado, CAPVId);
END;
