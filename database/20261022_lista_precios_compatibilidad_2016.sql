SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.LISTPRECIOS', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.LISTPRECIOS
  (
    EmpCod smallint NOT NULL,
    CliCod int NOT NULL,
    Especod smallint NOT NULL,
    Calibre char(10) NOT NULL,
    EnvCod smallint NOT NULL,
    LSPFecD datetime NOT NULL,
    LSPFecH datetime NOT NULL,
    MonCod smallint NOT NULL,
    LSPPrecioU money NULL,
    LSPIndTodos smallint NULL,
    LSPAnulado smallint NOT NULL CONSTRAINT DF_LISTPRECIOS_Anulado DEFAULT (0),
    LSPLoginC char(10) NULL,
    LSPFecC datetime NULL,
    LSPLoginM char(10) NULL,
    LSPFecM datetime NULL,
    LSPLoginA char(10) NULL,
    LSPFecA datetime NULL,
    CONSTRAINT PK_LISTPRECIOS PRIMARY KEY (EmpCod,CliCod,Especod,Calibre,EnvCod,LSPFecD,LSPFecH,MonCod)
  );
END;

-- Algunas instalaciones iniciales crearon solo las columnas usadas por las
-- validaciones de dependencias. Se completa la estructura GX8 sin borrar datos.
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'Especod') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD Especod smallint NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'Calibre') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD Calibre char(10) NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'EnvCod') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD EnvCod smallint NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPFecD') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPFecD datetime NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPFecH') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPFecH datetime NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPPrecioU') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPPrecioU money NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPIndTodos') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPIndTodos smallint NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPAnulado') IS NULL
  ALTER TABLE dbo.LISTPRECIOS ADD LSPAnulado smallint NOT NULL CONSTRAINT DF_LISTPRECIOS_Anulado DEFAULT (0) WITH VALUES;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPLoginC') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPLoginC char(10) NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPFecC') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPFecC datetime NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPLoginM') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPLoginM char(10) NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPFecM') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPFecM datetime NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPLoginA') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPLoginA char(10) NULL;
IF COL_LENGTH(N'dbo.LISTPRECIOS', N'LSPFecA') IS NULL ALTER TABLE dbo.LISTPRECIOS ADD LSPFecA datetime NULL;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.LISTPRECIOS') AND name=N'IX_LISTPRECIOS_EmpresaVigencia')
  CREATE INDEX IX_LISTPRECIOS_EmpresaVigencia ON dbo.LISTPRECIOS (EmpCod,LSPFecD,LSPFecH);

IF NOT EXISTS (SELECT 1 FROM dbo.PROGRAM1 WHERE SistCod=100 AND Modcod=9 AND ProgCod=10 AND ProgOPCod=1)
  INSERT INTO dbo.PROGRAM1 (SistCod,Modcod,ProgCod,ProgOPCod,ProgOPDes) VALUES (100,9,10,1,'Crea');
IF NOT EXISTS (SELECT 1 FROM dbo.PROGRAM1 WHERE SistCod=100 AND Modcod=9 AND ProgCod=10 AND ProgOPCod=2)
  INSERT INTO dbo.PROGRAM1 (SistCod,Modcod,ProgCod,ProgOPCod,ProgOPDes) VALUES (100,9,10,2,'Modifica');
IF NOT EXISTS (SELECT 1 FROM dbo.PROGRAM1 WHERE SistCod=100 AND Modcod=9 AND ProgCod=10 AND ProgOPCod=3)
  INSERT INTO dbo.PROGRAM1 (SistCod,Modcod,ProgCod,ProgOPCod,ProgOPDes) VALUES (100,9,10,3,'Anula');
ELSE
  UPDATE dbo.PROGRAM1 SET ProgOPDes='Anula' WHERE SistCod=100 AND Modcod=9 AND ProgCod=10 AND ProgOPCod=3;

COMMIT TRANSACTION;
